--- MAGNITUDE ANALYSIS
-- Find total customers by countries.
SELECT
   country,
   COUNT(customer_key) AS total_customers
FROM gold.dim_customers
GROUP BY country
ORDER BY total_customers DESC;

-- Find total customers by gender.
SELECT
   gender,
   COUNT(customer_key) AS total_customers
FROM gold.dim_customers
GROUP BY gender
ORDER BY total_customers DESC;

-- Find total products by category.
SELECT
   category,
   COUNT(product_key) AS total_products
FROM gold.dim_products
GROUP BY category
ORDER BY total_products DESC;

-- What is the average costs in each category.
SELECT
   category,
   AVG(cost) AS Average_cost
FROM gold.dim_products
GROUP BY category
ORDER BY Average_cost DESC;

-- What is the total revenue generated for each category?
SELECT p.category as Category,
   SUM(f.sales_amount) AS Revenue
FROM gold.fact_sales f
   LEFT JOIN gold.dim_products p
   ON  f.product_key = p.product_key
GROUP BY p.category
ORDER BY Revenue DESC;

-- Find total revenue is generated by each customers.
SELECT c.first_name AS customer,
   SUM(f.sales_amount) AS Revenue
FROM gold.fact_sales f
   LEFT JOIN gold.dim_customers c
   ON  f.customer_key = c.customer_key
GROUP BY c.first_name
ORDER BY Revenue DESC;

-- What is the distribution of sold items across countries?
SELECT c.country AS country,
   SUM(f.Quantity) AS total_item_sold
FROM gold.fact_sales f
   LEFT JOIN gold.dim_customers c
   ON  f.customer_key = c.customer_key
GROUP BY c.country
ORDER BY total_item_sold DESC;

-- RANKING ANALYSIS
-- Which 5 products generate the highest revenue 
SELECT TOP 5
   p.product_name as prodcuts,
   SUM(f.sales_amount) AS Revenue,
   RANK() OVER(ORDER BY SUM(f.sales_amount) DESC) AS ranking
FROM gold.fact_sales f
   LEFT JOIN gold.dim_products p
   ON  f.product_key = p.product_key
GROUP BY p.product_name;

-- Top 5 worst-performing products in terms of sales?
SELECT TOP 5
   p.product_name as prodcuts,
   SUM(f.sales_amount) AS Revenue,
   RANK() OVER(ORDER BY SUM(f.sales_amount) ASC) AS ranking
FROM gold.fact_sales f
   LEFT JOIN gold.dim_products p
   ON  f.product_key = p.product_key
GROUP BY p.product_name;

-- Top subcategories
SELECT TOP 5
   p.subcategory as subcategories,
   SUM(f.sales_amount) AS Revenue,
   RANK() OVER(ORDER BY SUM(f.sales_amount) DESC) AS ranking
FROM gold.fact_sales f
   LEFT JOIN gold.dim_products p
   ON  f.product_key = p.product_key
GROUP BY p.subcategory;

-- Worst subcategory
SELECT TOP 5
   p.subcategory as subcategories,
   SUM(f.sales_amount) AS Revenue,
   ROW_NUMBER() OVER(ORDER BY SUM(f.sales_amount) ASC) AS ranking
FROM gold.fact_sales f
   LEFT JOIN gold.dim_products p
   ON  f.product_key = p.product_key
GROUP BY p.subcategory;

-- Find the top 10 custoemrs who have generated the highest revenue 
-- and 3 customers with the fewest orders  placed.
SELECT TOP 10
   c.customer_key as customer_key,
   c.first_name AS customer,
   COUNT(DISTINCT f.order_number) AS total_orders
FROM gold.fact_sales f
   LEFT JOIN gold.dim_customers c
   ON  f.customer_key = c.customer_key
GROUP BY c.customer_key, c.first_name
ORDER BY  total_orders DESC;
